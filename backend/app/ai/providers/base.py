"""Base interfaces and unified data structures for LLM providers."""

from abc import ABC, abstractmethod
from typing import Any, AsyncGenerator, Dict, List, Literal, Optional
from pydantic import BaseModel, Field


class ToolCall(BaseModel):
    """Normalized function/tool call request emitted by an LLM."""

    id: str = Field(..., description="Unique tool call execution ID")
    name: str = Field(..., description="Target tool identifier")
    arguments: Dict[str, Any] = Field(default_factory=dict, description="Parsed arguments dictionary")
    thought_signature: Optional[str] = Field(default=None, description="Optional thought signature for reasoning models")


class ToolDefinition(BaseModel):
    """Specification of an executable tool provided to an LLM."""

    name: str
    description: str
    parameters: Dict[str, Any]  # JSON Schema definition


class ChatMessage(BaseModel):
    """Normalized chat message for conversational LLM interactions."""

    role: Literal["system", "user", "assistant", "tool"]
    content: Optional[str] = None
    name: Optional[str] = None
    tool_calls: Optional[List[ToolCall]] = None
    tool_call_id: Optional[str] = None


class LLMResponse(BaseModel):
    """Normalized response returned by any LLM provider."""

    content: Optional[str] = None
    role: str = "assistant"
    tool_calls: Optional[List[ToolCall]] = None
    finish_reason: Optional[str] = None
    usage: Optional[Dict[str, int]] = None
    model: Optional[str] = None
    provider: str


class AIProviderError(Exception):
    """Base exception for AI provider interaction failures."""

    def __init__(self, message: str, provider: str, status_code: Optional[int] = None):
        super().__init__(f"[{provider}] {message}")
        self.message = message
        self.provider = provider
        self.status_code = status_code


class AIProviderAuthenticationError(AIProviderError):
    """Raised when provider API key is missing, invalid, or unauthorized."""

    pass


class AIProviderRateLimitError(AIProviderError):
    """Raised when provider rate limits or quotas are exceeded."""

    pass


class AIProviderTransientError(AIProviderError):
    """Raised on network timeouts, connection resets, or 5xx provider outages (retryable)."""

    pass


class BaseLLMProvider(ABC):
    """Abstract interface defining required capabilities for any LLM backend."""

    def __init__(self, provider_name: str, model: str, timeout: float = 30.0):
        self.provider_name = provider_name
        self.model = model
        self.timeout = timeout

    @abstractmethod
    async def generate_response(
        self,
        messages: List[ChatMessage],
        tools: Optional[List[ToolDefinition]] = None,
        response_schema: Optional[Dict[str, Any]] = None,
        temperature: float = 0.7,
        max_tokens: int = 1024,
    ) -> LLMResponse:
        """Generates a complete response turn with optional tool calls."""
        pass

    @abstractmethod
    async def generate_stream(
        self,
        messages: List[ChatMessage],
        tools: Optional[List[ToolDefinition]] = None,
        temperature: float = 0.7,
        max_tokens: int = 1024,
    ) -> AsyncGenerator[str, None]:
        """Streams text chunks as they are generated by the model."""
        pass
